// Pulls every provider logo models.dev publishes into one sprite the UI ships.
// Run with `bun run icons:providers`; the output is committed, so the app never
// reaches for the network to draw a logo.
import { mkdir, writeFile } from "node:fs/promises";
import { join } from "node:path";

const BASE = "https://models.dev";
const OUT = join(import.meta.dir, "..", "apps", "desktop", "ui", "src", "provider-icons");
const FALLBACK_ID = "default";

async function text(url: string): Promise<string> {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${url}: ${res.status}`);
  return res.text();
}

/**
 * One logo as a `<symbol>`. Ids inside a logo (gradients, clip paths) are
 * prefixed with the provider id: a sprite is one document, and two logos that
 * both call their gradient `a` would otherwise paint with each other's.
 */
function toSymbol(id: string, svg: string): string {
  const open = svg.match(/<svg\b[^>]*>/i)?.[0];
  if (!open) throw new Error(`${id}: not an svg`);
  const viewBox =
    open.match(/viewBox="([^"]+)"/i)?.[1] ??
    `0 0 ${open.match(/width="(\d+(?:\.\d+)?)/i)?.[1] ?? 24} ${open.match(/height="(\d+(?:\.\d+)?)/i)?.[1] ?? 24}`;
  const body = svg
    .slice(svg.indexOf(open) + open.length, svg.lastIndexOf("</svg>"))
    .replace(/<!--[\s\S]*?-->/g, "")
    // Drawn at 14px, a hundredth of a unit is already below a device pixel;
    // the six-decimal coordinates design tools export are most of the weight.
    .replace(/-?\d*\.\d{3,}/g, (n) => String(Number(Number(n).toFixed(2))))
    .replace(/\bid="([^"]+)"/g, (_, v) => `id="${id}-${v}"`)
    .replace(/url\(#([^)]+)\)/g, (_, v) => `url(#${id}-${v})`)
    .replace(/href="#([^"]+)"/g, (_, v) => `href="#${id}-${v}"`)
    .replace(/\s*\n\s*/g, " ")
    .trim();
  // Paint set on the logo's own root — `fill="none"` on a stroked mark — would
  // be lost with the root, and the shapes would fill solid instead.
  const paint = [...open.matchAll(/\s(fill|stroke|stroke-width|stroke-linecap|stroke-linejoin|fill-rule|clip-rule)="[^"]*"/gi)]
    .map((m) => m[0])
    .join("");
  return `<symbol id="${id}" viewBox="${viewBox}">${paint ? `<g${paint}>${body}</g>` : body}</symbol>`;
}

const providers = Object.keys(JSON.parse(await text(`${BASE}/api.json`))).sort();
// models.dev answers an id it has no logo for with a generic mark rather than
// a 404, so a logo identical to the one for a made-up id is not a logo.
const fallback = await text(`${BASE}/logos/__no_such_provider__.svg`);

const logos = new Map<string, string>();
const queue = [...providers];
await Promise.all(
  Array.from({ length: 12 }, async () => {
    for (let id = queue.shift(); id; id = queue.shift()) {
      const svg = await text(`${BASE}/logos/${id}.svg`).catch(() => fallback);
      if (svg.trim() === fallback.trim()) continue;
      // A logo that is a bitmap in an svg wrapper cannot take the text colour,
      // so it would be the one mark in the toolbar that ignores the theme.
      if (/<image\b/i.test(svg)) continue;
      logos.set(id, svg);
    }
  }),
);

// Regional and plan variants of one provider ship the same file. Draw it once
// and point every id at it.
const ids = [...logos.keys()].sort();
const owner = new Map<string, string>();
const alias: Record<string, string> = {};
for (const id of ids) {
  const key = logos.get(id)!.trim();
  const first = owner.get(key);
  if (first) alias[id] = first;
  else owner.set(key, id);
}
// A logo that is a traced illustration rather than a mark costs more than the
// next twenty together and reads as a smudge at 14px; the generic mark is the
// better drawing at that size.
const MAX_SYMBOL = 16_000;
const drawnAll = ids.filter((id) => !alias[id]).map((id) => ({ id, symbol: toSymbol(id, logos.get(id)!) }));
const heavy = new Set(drawnAll.filter((d) => d.symbol.length > MAX_SYMBOL).map((d) => d.id));
for (const id of ids) {
  if (heavy.has(alias[id] ?? id)) {
    logos.delete(id);
    delete alias[id];
  }
}
ids.splice(0, ids.length, ...ids.filter((id) => logos.has(id)));
const drawn = drawnAll.filter((d) => !heavy.has(d.id));
const symbols = [toSymbol(FALLBACK_ID, fallback), ...drawn.map((d) => d.symbol)];
if (heavy.size) console.log(`too heavy, left to the generic mark: ${[...heavy].join(", ")}`);

await mkdir(OUT, { recursive: true });
await writeFile(
  join(OUT, "sprite.svg"),
  `<svg xmlns="http://www.w3.org/2000/svg">\n${symbols.join("\n")}\n</svg>\n`,
);
await writeFile(
  join(OUT, "names.ts"),
  `// Generated by scripts/provider-icons.ts from ${BASE}/logos — do not edit.\n\n` +
    `export const PROVIDER_ICON_FALLBACK = "${FALLBACK_ID}";\n\n` +
    `/** Provider id → the symbol in sprite.svg that draws it. */\n` +
    `export const PROVIDER_ICONS: Readonly<Record<string, string>> = {\n` +
    ids.map((id) => `  ${JSON.stringify(id)}: ${JSON.stringify(alias[id] ?? id)},`).join("\n") +
    `\n};\n`,
);
console.log(`${ids.length} of ${providers.length} providers have a logo, ${drawn.length} distinct`);
